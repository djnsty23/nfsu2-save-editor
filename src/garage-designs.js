// The ready-made garage: ten finished cars that ship with the editor, each with its looks, performance parts and
// five tuned setups. The data lives in src/garage-data.js, generated from one career by tools/garage-refresh.mjs.
//
// Only derived values ship: the car's game data name, visual part hashes, part flags, unique flags, setup bytes,
// the tuning rule each setup followed and the save's date. No profile name, money, stage, race result, file name or
// anything else that says whose career it came from. checkGarageData enforces that with an allowlist: fixed keys,
// fixed-length hex, integers in range and car names the game data uses. Anything else, a stray string included,
// fails the check, so a profile name cannot ride along under any key.
import { CAR_NAMES } from './car-names.js';

export const SCHEMA = 1;
export const VISUAL_COUNT = 170;
export const PERF_COUNT = 68;
export const OWNED_BYTES = 9;
export const UNIQUE_COUNT = 9;
export const SETUP_SIZE = 41;
export const SETUP_COUNT = 5;
export const MAX_CARS = 10;

/** Where each setup's tuning came from, by code. The panel and docs show the words. */
export const TUNING_RULES = {
  kept: 'kept as tuned in game',
  street: 'Corolla Street X sliders',
  streetHeavy: 'Corolla Street X sliders, rear ride height stock',
  dragRear: 'Corolla drag sliders (rear-drive launch)',
  dragFront: 'Civic drag sliders (front-drive launch)',
  drift: 'drift sliders',
};

/** Why a car's setups follow their rules, one line per car, by code. */
export const CAR_REASONS = {
  template: 'The Corolla Street X setup itself: kept byte for byte, the template the other cars start from.',
  rwd: 'Light rear-drive car like the Corolla: its Street X sliders carry over as they are.',
  rwdHeavy: 'Heavy, powerful rear-drive car: Corolla Street X sliders, but the rear ride height stays stock to keep traction out of corners.',
  awd: 'All-wheel drive pulls it straight: the Corolla\'s stiff, high rear helps it turn in.',
  fwd: 'Front-wheel drive: Corolla sliders help it rotate in corners, but drag uses the Civic\'s front-drive launch.',
};

const HEX = (bytes) => new RegExp(`^[0-9a-f]{${bytes * 2}}$`);
const RE = {
  visual: HEX(VISUAL_COUNT * 4), perf: HEX(PERF_COUNT), owned: HEX(OWNED_BYTES), setup: HEX(SETUP_SIZE),
  date: /^\d{4}-\d{2}-\d{2}$/,
};
const CAR_KEYS = ['car', 'reason', 'visual', 'perf', 'owned', 'uniques', 'setups', 'tuning'];
const TOP_KEYS = ['schema', 'saved', 'cars'];
const sameKeys = (o, keys) => o && typeof o === 'object' && !Array.isArray(o) && Object.keys(o).length === keys.length && keys.every((k) => Object.hasOwn(o, k));

/**
 * The allowlist. Returns a list of problems; empty means the data may ship. Every string must be one of the known
 * shapes: a car name from the game data, a rule or reason code, a date, or hex of a fixed length.
 */
export function checkGarageData(data) {
  const bad = [];
  if (!sameKeys(data, TOP_KEYS)) return [`top level must have exactly ${TOP_KEYS.join(', ')}`];
  if (data.schema !== SCHEMA) bad.push(`schema must be ${SCHEMA}`);
  if (typeof data.saved !== 'string' || !RE.date.test(data.saved)) bad.push('saved must be a YYYY-MM-DD date');
  if (!Array.isArray(data.cars) || data.cars.length < 1 || data.cars.length > MAX_CARS) return [...bad, `cars must hold 1 to ${MAX_CARS} cars`];
  data.cars.forEach((c, i) => {
    const at = `car ${i + 1}`;
    if (!sameKeys(c, CAR_KEYS)) { bad.push(`${at} must have exactly ${CAR_KEYS.join(', ')}`); return; }
    if (typeof c.car !== 'string' || !Object.hasOwn(CAR_NAMES, c.car)) bad.push(`${at}: unknown car`);
    if (typeof c.reason !== 'string' || !Object.hasOwn(CAR_REASONS, c.reason)) bad.push(`${at}: unknown reason`);
    for (const k of ['visual', 'perf', 'owned']) if (typeof c[k] !== 'string' || !RE[k].test(c[k])) bad.push(`${at}: ${k} is not hex of the right length`);
    if (!Array.isArray(c.uniques) || c.uniques.length !== UNIQUE_COUNT || !c.uniques.every((u) => u === 0 || u === 1)) bad.push(`${at}: uniques must be ${UNIQUE_COUNT} zeros and ones`);
    if (!Array.isArray(c.setups) || c.setups.length !== SETUP_COUNT || !c.setups.every((s) => typeof s === 'string' && RE.setup.test(s))) bad.push(`${at}: setups must be ${SETUP_COUNT} hex strings`);
    if (!Array.isArray(c.tuning) || c.tuning.length !== SETUP_COUNT || !c.tuning.every((t) => typeof t === 'string' && Object.hasOwn(TUNING_RULES, t))) bad.push(`${at}: tuning must be ${SETUP_COUNT} rule codes`);
  });
  return bad;
}

/** Same check on the text of src/garage-data.js: the generated wrapper and nothing else around the JSON. */
export function checkGarageModuleText(text) {
  const m = /^\/\/ Generated by tools\/garage-refresh\.mjs\. Do not edit\.\nexport default (\{.*\});\n$/s.exec(text);
  if (!m) return ['src/garage-data.js must be the generated wrapper around one JSON object'];
  let data;
  try { data = JSON.parse(m[1]); } catch (err) { return [`src/garage-data.js does not parse: ${err.message}`]; }
  return checkGarageData(data);
}

export function moduleText(data) {
  return `// Generated by tools/garage-refresh.mjs. Do not edit.\nexport default ${JSON.stringify(data, null, 1)};\n`;
}

export const toHex = (bytes) => Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
export function fromHex(text) {
  const out = new Uint8Array(text.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(text.slice(i * 2, i * 2 + 2), 16);
  return out;
}
/** The 170 visual part hashes of a design. */
export function visualRefs(design) {
  const b = fromHex(design.visual), dv = new DataView(b.buffer);
  return Array.from({ length: VISUAL_COUNT }, (_, i) => dv.getUint32(i * 4, true));
}
