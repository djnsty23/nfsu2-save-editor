// The ready-made garage that ships: it passes the allowlist, and the allowlist and the name check catch a profile
// name planted anywhere. Needs no game files.
// Usage: node test/garage.test.mjs
import { readFileSync } from 'node:fs';
import * as designs from '../src/garage-designs.js';
import garage from '../src/garage-data.js';
import { nameLeaks } from '../tools/garage-refresh.mjs';

let pass = 0, fail = 0;
const check = (name, ok, detail = '') => { ok ? pass++ : fail++; console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? `  [${detail}]` : ''}`); };
const text = readFileSync(new URL('../src/garage-data.js', import.meta.url), 'utf8');
const copy = () => JSON.parse(JSON.stringify(garage));
const rejects = (data, re) => { const bad = designs.checkGarageData(data); return bad.length > 0 && bad.some((b) => re.test(b)); };

check('the shipped garage passes the allowlist', designs.checkGarageData(garage).length === 0, designs.checkGarageData(garage).join('; '));
check('the shipped file is the generated wrapper and nothing else', designs.checkGarageModuleText(text).length === 0, designs.checkGarageModuleText(text).join('; '));
check('it holds ten cars, each with five setups and five rule codes', garage.cars.length === 10 && garage.cars.every((c) => c.setups.length === 5 && c.tuning.length === 5));
const corolla = garage.cars.find((c) => c.reason === 'template');
check('the Corolla is the template and its Street X is kept as tuned', corolla?.car === 'COROLLA' && corolla.tuning[3] === 'kept');
check('every car has looks: at least 40 visual parts set', garage.cars.every((c) => designs.visualRefs(c).filter((v) => v !== 0).length >= 40));

// Plants. The name is made up for the test: a real profile name never goes in a committed file.
const NAME = 'Zorblax77';
let d = copy(); d.player = NAME;
check('plant: a name under an extra top-level key is refused', rejects(d, /top level/));
d = copy(); d.cars[0].owner = NAME;
check('plant: a name under an extra car key is refused', rejects(d, /must have exactly/));
d = copy(); d.cars[0].car = NAME;
check('plant: a name in place of the car is refused', rejects(d, /unknown car/));
d = copy(); d.cars[0].reason = NAME;
check('plant: a name in place of the reason is refused', rejects(d, /unknown reason/));
d = copy(); d.saved = NAME;
check('plant: a name in place of the date is refused', rejects(d, /date/));
d = copy(); d.cars[0].tuning[2] = NAME;
check('plant: a name in place of a rule code is refused', rejects(d, /rule codes/));
d = copy(); d.cars[0].visual += Buffer.from(NAME).toString('hex');
check('plant: a name added to the visual hex is refused by length', rejects(d, /visual is not hex/));
// Hex of the same length passes the allowlist by design: the generator's name check below is what catches it.
d = copy(); d.cars[0].visual = d.cars[0].visual.slice(0, -18) + Buffer.from(NAME).toString('hex');
check('plant: a name swapped into the visual hex is caught by the name check', nameLeaks(JSON.stringify(d), NAME).includes('hex'));
d = copy(); d.cars[0].uniques[0] = NAME;
check('plant: a name in the unique flags is refused', rejects(d, /uniques/));
const wrapped = text.replace('// Generated by', `// ${NAME}\n// Generated by`);
check('plant: a name in a comment of the module is refused', designs.checkGarageModuleText(wrapped).length > 0);

// The generator's last gate before it writes anything: the career's own name in any spelling.
check('the name check finds plain text in any case', nameLeaks(`x ${NAME.toUpperCase()} x`, NAME).includes('plain text'));
check('the name check finds UTF-16', nameLeaks(`x ${[...NAME].map((c) => `${c}\u0000`).join('')} x`, NAME).includes('UTF-16'));
check('the name check finds hex', nameLeaks(`"visual": "00${Buffer.from(NAME).toString('hex')}00"`, NAME).includes('hex'));
check('the shipped data and table carry no planted name', nameLeaks(text, NAME).length === 0);
const doc = readFileSync(new URL('../docs/garage-defaults.md', import.meta.url), 'utf8');
check('the per-car table lists every car', garage.cars.length === doc.split('\n').filter((l) => /^\| [A-Z]/.test(l) && !l.startsWith('| Car ')).length);

console.log(`\n${pass}/${pass + fail} pass`);
process.exitCode = fail ? 1 : 0;
